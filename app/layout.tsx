import type { Metadata, Viewport } from "next";
import { Spline_Sans } from "next/font/google";
import localFont from "next/font/local";
import { preconnect } from "react-dom";
import "./globals.css";
import { ConvexClientProvider } from "./ConvexClientProvider";
import { ServiceWorkerRegistration } from "./ServiceWorkerRegistration";
import { AppHeightSync } from "./AppHeightSync";
import { APP_HEIGHT_SCRIPT } from "@/lib/app-height";
import splashDevices from "@/lib/ios-splash-devices.json";

// Fonts are self-hosted and preloaded by next/font, so first paint never waits
// on fonts.googleapis.com.
const splineSans = Spline_Sans({
  subsets: ["latin"],
  variable: "--font-spline-sans",
  display: "swap",
});

// Subset of Material Symbols containing only the icons the app uses
// (regenerate with `bun run icons`). `block` keeps ligature names such as
// "chevron_right" invisible instead of flashing as text while loading.
const materialSymbols = localFont({
  src: "./fonts/material-symbols-outlined.woff2",
  variable: "--font-material-symbols",
  display: "block",
  adjustFontFallback: false,
});

// Keep in sync with --background in globals.css and scripts/generate-pwa-assets.mjs.
const BACKGROUND = "#121212";

export const metadata: Metadata = {
  title: "Mygraines",
  description: "A simple migraine tracker.",
  applicationName: "Mygraines",
  appleWebApp: {
    capable: true,
    // Label under the home-screen icon.
    title: "Mygraines",
    // Content draws under the status bar, so the launch image, status bar and
    // app all share one background and nothing flashes between them.
    statusBarStyle: "black-translucent",
    // iOS only shows a launch image when one matches the device exactly;
    // generated by `bun run pwa-assets` from lib/ios-splash-devices.json.
    startupImage: splashDevices.map(({ width, height, ratio }) => ({
      url: `/splash/${width * ratio}x${height * ratio}.png`,
      media:
        `screen and (device-width: ${width}px) and (device-height: ${height}px)` +
        ` and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait)`,
    })),
  },
  formatDetection: { telephone: false },
  // app/favicon.ico is picked up automatically; only the iOS icon is explicit.
  icons: {
    apple: [
      { url: "/icons/apple-touch-icon.png", sizes: "180x180", type: "image/png" },
    ],
  },
  // Next only emits the unprefixed mobile-web-app-capable; iOS < 17 needs this.
  other: { "apple-mobile-web-app-capable": "yes" },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  // Stops iOS from zooming the page when a text field is focused.
  maximumScale: 1,
  // Lets the app draw edge to edge; padding uses env(safe-area-inset-*).
  viewportFit: "cover",
  themeColor: BACKGROUND,
  colorScheme: "dark",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Open the Convex connection's DNS/TLS handshake while the bundle is parsed.
  const convexUrl = process.env.NEXT_PUBLIC_CONVEX_URL;
  if (convexUrl) preconnect(convexUrl);

  return (
    <html
      lang="en"
      className={`${splineSans.variable} ${materialSymbols.variable}`}
      // Inline so the very first paint is already dark, before any CSS arrives.
      style={{ backgroundColor: BACKGROUND }}
    >
      <head>
        {/* Sizes the app from the real screen height before first paint. */}
        <script dangerouslySetInnerHTML={{ __html: APP_HEIGHT_SCRIPT }} />
      </head>
      <body className="antialiased bg-background-dark text-text-dark">
        <ConvexClientProvider>{children}</ConvexClientProvider>
        <ServiceWorkerRegistration />
        <AppHeightSync />
      </body>
    </html>
  );
}
